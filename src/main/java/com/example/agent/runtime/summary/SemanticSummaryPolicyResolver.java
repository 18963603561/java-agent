@Component
public class SemanticSummaryPolicyResolver {

    /**
     * ?????????
     *
     * @param input ????
     * @return ????
     */
    public SemanticSummaryScenarioDecision resolveScenarioDecision(StepSummaryBuildInput input) {
        // ?????????????????/??/??/????????????
        // ????????????????????
        if (input == null) {
            // ???????????????
            return SemanticSummaryScenarioDecision.defaultDecision();
        }
        // ??????????
        SummaryRequestOverrides overrides = SummaryRequestOverrides.fromInput(input);
        // ???????????????????????
        if (overrides != null && StringUtils.hasText(overrides.getScenario())) {
            // ?????????
            SemanticSummaryScenario scenario = SemanticSummaryScenario.of(overrides.getScenario());
            // ?????????
            return SemanticSummaryScenarioDecision.of(scenario, SemanticSummaryScenarioSource.OVERRIDE);
        }
        // ????????????????
        Map<String, Object> outputMap = resolveOutputMap(input.getOutput());
        // ??????????
        String resultKind = resolveResultKind(outputMap);
        // ????????????????????????
        if (StringUtils.hasText(resultKind)) {
            // ?????????
            return SemanticSummaryScenarioDecision.of(SemanticSummaryScenario.of("result:" + resultKind),
                    SemanticSummaryScenarioSource.INFERRED);
        }
        // ?????????????????????
        if (hasDecision(outputMap)) {
            // ?????????
            return SemanticSummaryScenarioDecision.of(SemanticSummaryScenario.of("decision"),
                    SemanticSummaryScenarioSource.INFERRED);
        }
        // ???????
        String stepType = input.getStepType();
        // ?????????????????????
        if (StringUtils.hasText(stepType)) {
            // ?????????
            return SemanticSummaryScenarioDecision.of(SemanticSummaryScenario.of("step:" + stepType),
                    SemanticSummaryScenarioSource.INFERRED);
        }
        // ???????
        String toolName = input.getToolName();
        // ?????????????????????
        if (StringUtils.hasText(toolName)) {
            // ?????????
            return SemanticSummaryScenarioDecision.of(SemanticSummaryScenario.of("tool"),
                    SemanticSummaryScenarioSource.INFERRED);
        }
        // ?????????
        return SemanticSummaryScenarioDecision.defaultDecision();
    }

    /**
     * ???????
     *
     * @param input ????
     * @return ????
     */
    public SemanticSummaryScenario resolveScenario(StepSummaryBuildInput input) {
        // ?????????????
        SemanticSummaryScenarioDecision decision = resolveScenarioDecision(input);
        // ???????
        return decision.getScenario();
    }

    private Map<String, Object> resolveOutputMap(Object output) {
        // ????????????????
        if (output instanceof Map<?, ?> map && !map.isEmpty()) {
            // ?????????????????
            Map<String, Object> copied = new LinkedHashMap<>();
            // ????????????????
            for (Map.Entry<?, ?> entry : map.entrySet()) {
                // ???????????????
                copied.put(String.valueOf(entry.getKey()), entry.getValue());
            }
            // ???????????
            return copied;
        }
        // ???????????
        return Map.of();
    }

    private String resolveResultKind(Map<String, Object> outputMap) {
        // ??????????????????
        if (outputMap == null || outputMap.isEmpty()) {
            // ?????????????
            return null;
        }
        // ?? result ?????
        Object resultObj = outputMap.get(RuntimeOutputKeys.RESULT);
        // ?? result ?????????????????
        if (!(resultObj instanceof Map<?, ?> resultMap)) {
            // ??????????????
            return null;
        }
        // ?? kind ?????
        Object kind = resultMap.get("kind");
        // ?? kind ???????? null?
        return kind == null ? null : String.valueOf(kind).trim().toLowerCase();
    }

    private boolean hasDecision(Map<String, Object> outputMap) {
        // ?????????????????
        if (outputMap == null || outputMap.isEmpty()) {
            // ?? false?????????
            return false;
        }
        // ???????????
        Object decision = outputMap.get(RuntimeOutputKeys.DECISION);
        // ???????????
        return decision != null;
    }
}
