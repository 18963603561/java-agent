package com.example.agent.runtime.structured;

/**
 * 结构化结果类型。
 */
/**
 * ResultKind 表示步骤执行后结构化结果的语义类型。
 *
 * 该枚举用于：
 * 1. 标识 StructuredResult 的业务语义分类；
 * 2. 指导 Runtime / Planner / UI 对结果进行后续处理；
 * 3. 支持不同类型结果的统一归一化与消费。
 *
 * 设计原则：
 * - 每一种 ResultKind 对应一种稳定的“语义契约”；
 * - 不直接绑定具体工具或模型输出格式；
 * - 由 StructuredExtractorRegistry 统一收口映射。
 */
public enum ResultKind {

    /**
     * 表匹配结果。
     * 用于数据治理/元数据检索场景中，
     * 表示匹配到的相关数据表集合。
     *
     * 典型来源：
     * - 表结构搜索工具
     * - 元数据匹配模型
     */
    TABLE_MATCHES,

    /**
     * SQL 语句结果。
     * 表示模型或规划器生成的可执行 SQL。
     *
     * 典型来源：
     * - SQL 生成模型
     * - 查询规划步骤
     *
     * 消费方：
     * - SQL 执行工具
     * - 人工确认界面
     */
    SQL,

    /**
     * 查询结果集。
     * 表示数据库执行后返回的记录数据（表格数据）。
     *
     * 典型来源：
     * - JDBC 查询
     * - 数据库执行工具
     *
     * 语义要求：
     * - 应包含字段列表与行数据
     */
    RECORDSET,

    /**
     * 实体列表。
     * 表示抽取后的结构化实体集合，
     * 例如手机号、身份证、设备号等。
     *
     * 典型来源：
     * - 信息抽取模型
     * - 规则引擎
     */
    ENTITY_LIST,

    /**
     * 决策类结果。
     * 表示规划/判断/策略选择的决策输出，
     * 例如是否需要重试、是否需要调用工具等。
     *
     * 典型来源：
     * - Planner
     * - 决策模型
     */
    DECISION,

    /**
     * 诊断结果。
     * 用于问题分析、异常排查场景，
     * 表示系统状态或问题原因的分析结论。
     *
     * 典型来源：
     * - 日志分析模型
     * - 运维诊断工具
     */
    DIAGNOSIS,

    /**
     * 文档引用。
     * 表示从知识库或外部文档中检索出的引用内容。
     *
     * 典型来源：
     * - RAG 检索
     * - 向量数据库搜索
     *
     * 通常包含：
     * - 文档片段
     * - 来源标识
     */
    DOCUMENT_CITATIONS,

    /**
     * 错误结果。
     * 表示步骤执行失败或结构化解析失败。
     *
     * 注意：
     * - ERROR 不等同于 Step 状态 FAILED；
     * - 也可能是工具成功执行但返回业务错误。
     */
    ERROR
}

